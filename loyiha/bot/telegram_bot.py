def start_bot() -> None:
    """Initialize and run Telegram Bot with clean UI and Webhook/Polling switcher."""
    global telegram_app
    if not TELEGRAM_BOT_TOKEN:
        logging.warning("TELEGRAM_BOT_TOKEN missing.")
        return

    telegram_app = ApplicationBuilder().token(TELEGRAM_BOT_TOKEN).post_init(post_init).build()

    # Register Command Handlers
    telegram_app.add_handler(CommandHandler("start", start))
    telegram_app.add_handler(CommandHandler("status", status))
    telegram_app.add_handler(CommandHandler("chart", chart))
    telegram_app.add_handler(CommandHandler("backtest", backtest))
    telegram_app.add_handler(CommandHandler("risk", risk_cmd))
    telegram_app.add_handler(CommandHandler("settings", settings))
    telegram_app.add_handler(CommandHandler("help", help_cmd))

    # Register Media Handlers
    telegram_app.add_handler(MessageHandler(filters.PHOTO, photo_handler))
    telegram_app.add_handler(MessageHandler(filters.Document.ALL, document_handler))
    telegram_app.add_handler(MessageHandler(filters.TEXT & ~filters.COMMAND, price_handler))

    if USE_WEBHOOK and WEBHOOK_URL:
        logging.info(f"Starting Telegram Bot in WEBHOOK mode on {WEBHOOK_LISTEN}:{WEBHOOK_PORT}...")
        try:
            telegram_app.run_webhook(
                listen=WEBHOOK_LISTEN,
                port=WEBHOOK_PORT,
                url_path=TELEGRAM_BOT_TOKEN,
                webhook_url=f"{WEBHOOK_URL}/{TELEGRAM_BOT_TOKEN}"
            )
        except Exception as e:
            logging.error(f"Webhook execution failed: {e}. Falling back to Polling...")
            telegram_app.run_polling()
    else:
        logging.info("Starting Telegram Bot in POLLING mode...")
        try:
            telegram_app.run_polling()
        except Exception as e:
            logging.error("Telegram bot error: %s", e)
